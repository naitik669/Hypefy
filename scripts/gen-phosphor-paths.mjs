#!/usr/bin/env node
/**
 * Writes apps/mobile/src/phosphor-paths.ts from the installed
 * @phosphor-icons/react.
 *
 * The data is committed rather than extracted at runtime, because
 * @phosphor-icons/react is a React DOM package and importing it from the
 * native app would pull react-dom into a bundle that has no DOM. So the
 * geometry is copied across the boundary once, here, and
 * tests/mobile-icons.test.ts re-runs this extraction and fails if the
 * committed copy has drifted — which is what makes the copy safe.
 *
 *   node scripts/gen-phosphor-paths.mjs
 */
import { writeFileSync } from "node:fs";
import { extract, PHOSPHOR_VIEW_BOX, WEIGHTS, ICONS } from "./phosphor-extract.mjs";

const OUT = "apps/mobile/src/phosphor-paths.ts";

const header = `// GENERATED by scripts/gen-phosphor-paths.mjs — do not edit by hand.
//
// Path data lifted from @phosphor-icons/react, the package the web already
// draws its bottom bar with. Copied rather than imported because that is a
// React DOM package and the native bundle has no DOM.
//
// Phosphor draws on a 256x256 grid; Lucide, which the rest of the app uses,
// draws on 24x24. The viewBox below travels with these paths for that
// reason.
//
// tests/mobile-icons.test.ts re-runs the extraction against node_modules and
// fails if this file has drifted, so a Phosphor upgrade that reshapes an
// icon cannot leave the phone drawing last version's.
//
// Weights match the web's rule in BottomNav.tsx: fill when the tab is
// active, regular when it is not.
`;

async function main() {
  const data = {};
  for (const icon of ICONS) data[icon] = await extract(icon);

  const body =
    `${header}
export const PHOSPHOR_VIEW_BOX = ${JSON.stringify(PHOSPHOR_VIEW_BOX)};

export type PhosphorIconName = ${ICONS.map((i) => JSON.stringify(i)).join(" | ")};
export type PhosphorWeight = ${WEIGHTS.map((w) => JSON.stringify(w)).join(" | ")};

export const PHOSPHOR_PATHS: Readonly<
  Record<PhosphorIconName, Readonly<Record<PhosphorWeight, readonly string[]>>>
> = ${JSON.stringify(data, null, 2)} as const;
`;

  writeFileSync(OUT, body);
  const count = ICONS.length * WEIGHTS.length;
  console.log(`wrote ${OUT}: ${ICONS.length} icons x ${WEIGHTS.length} weights = ${count} paths`);
}

await main();
